// Package editor собирает команду запуска редактора для одного файла и
// возвращает его права после выхода (Фаза 11, GUIDE-03) — единственная
// формула запуска редактора в проекте.
//
// В аргументы уходит только путь — никогда содержимое: файл секретов
// целиком состоит из значений, а таблица процессов видна всей машине.
// Оболочка не задействована ни в одной форме: строка переменной редактора
// разбивается на поля, первое поле ищется в путях исполняемых файлов
// штатным средством пакета запуска процессов (exec.LookPath), остальные
// становятся аргументами перед путём. Пакет зависит только от стандартной
// библиотеки.
package editor

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"strings"
)

// ErrNoEditor — редактор не найден в PATH.
var ErrNoEditor = errors.New("редактор не найден")

// Command собирает команду запуска редактора для файла path. Порядок
// предпочтения: переменная визуального редактора (VISUAL), затем переменная
// редактора (EDITOR), затем vi.
//
// Значение из одних пробельных символов непусто и потому не перехватывается
// проверкой на пустоту, а разбиение на поля (strings.Fields) даёт по нему
// пустой срез — в этом случае берётся vi: без этой проверки обращение к
// первому полю уронило бы процесс паникой вместо понятного сообщения.
//
// Ненайденный исполняемый файл — отказ, обёрнутый ErrNoEditor, с именем
// того, что искали. Стандартные потоки команде НЕ назначаются: их
// назначает вызывающий — подкоманда напрямую, интерфейс через механизм
// передачи терминала, и назначенные заранее потоки отняли бы у механизма
// это право.
func Command(path string) (*exec.Cmd, error) {
	editor := os.Getenv("VISUAL")
	if editor == "" {
		editor = os.Getenv("EDITOR")
	}
	if editor == "" {
		editor = "vi"
	}

	fields := strings.Fields(editor)
	if len(fields) == 0 {
		fields = []string{"vi"}
	}

	bin, err := exec.LookPath(fields[0])
	if err != nil {
		return nil, fmt.Errorf("editor: %q не найден в PATH: %w", fields[0], ErrNoEditor)
	}

	args := append(append([]string{}, fields[1:]...), path)
	return exec.Command(bin, args...), nil
}

// RestorePerms возвращает файлу path права 0600. Редактор мог записать файл
// заново по маске процесса, и без возврата прав файл секретов стал бы
// читаемым всей машине, а проверка прав при следующем чтении отказалась бы
// его открывать вовсе.
func RestorePerms(path string) error {
	if err := os.Chmod(path, 0o600); err != nil {
		return fmt.Errorf("editor: не удалось вернуть права 0600 файлу %s: %w", path, err)
	}
	return nil
}
