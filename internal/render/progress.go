package render

import (
	"fmt"
	"io"
)

// Progress — единственная точка поэтапного вывода прогресса воспроизведения
// (CLI-02): код на коммите, проверка Docker, тяга образа, подъём контейнера.
// Значение хранится по значению, а не по указателю — вызывающий код может
// свободно копировать и передавать Progress без риска гонки на общем
// состоянии, потому что состояния у него нет вовсе, кроме io.Writer.
type Progress struct {
	W io.Writer
}

// Stage печатает одну строку этапа с двумя ведущими пробелами (как в
// примере вывода из idea) и переводом строки. Нулевое значение Progress
// (W == nil) безопасно: Stage молча ничего не делает. Ошибка записи
// игнорируется — прогресс служебный, его сбой не должен ронять
// воспроизведение, в отличие от основного вывода render.Job/render.Env, где
// ошибка возвращается вызывающему.
//
// Сигнатура принимает только строки и числа, которые формирует вызывающий
// код: ни окружение, ни доменные типы provider/env сюда не попадают —
// значение переменной физически не может оказаться в прогрессе.
func (p Progress) Stage(format string, args ...any) {
	if p.W == nil {
		return
	}
	fmt.Fprintf(p.W, "  "+format+"\n", args...)
}

// truncate обрезает s до n символов, добавляя многоточие при обрезке.
func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n]) + "…"
}
