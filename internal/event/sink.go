package event

// Sink — интерфейс подписчика на события. Единственный метод — потому что
// подписчик отличается только тем, что он делает с событием: печатает,
// кладёт в канал программы Bubble Tea или выбрасывает.
//
// Emit может вызываться из нескольких горутин одновременно: вывод шагов
// приходит из горутины, копирующей стандартный вывод дочернего процесса, а
// этапы — из основной. Синхронизация — забота реализации, а не вызывающего;
// иначе длинные операции в отдельных горутинах (Фаза 9) потребовали бы
// править доменные пакеты.
type Sink interface {
	Emit(Event)
}

// Emitter — носитель, который держит доменный пакет вместо Sink напрямую,
// ровно чтобы не проверять на nil в каждой из двух десятков точек. Форма
// выбрана намеренно той же, что у нынешнего носителя прогресса
// (render.Progress): значение без внутреннего состояния, которое можно
// свободно копировать и передавать в горутину, и нулевое значение которого
// безопасно.
type Emitter struct {
	Sink Sink
}

// Emit передаёт e в Sink. При нулевом Sink молча ничего не делает — доменный
// пакет без подписчика молча ничего не эмитит, как сегодня молчит нулевой
// прогресс.
func (e Emitter) Emit(ev Event) {
	if e.Sink == nil {
		return
	}
	e.Sink.Emit(ev)
}
