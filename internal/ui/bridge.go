package ui

import (
	"sync"

	tea "charm.land/bubbletea/v2"

	"github.com/f3rym/ci-shell/internal/event"
)

// EventMsg — сообщение Bubble Tea с событием фазы 8. Интерфейс намеренно не
// разбирает событие здесь: разбирать его должна модель в своей функции
// обновления — это и есть архитектура, ради которой фаза 8 завела события
// вместо строк.
type EventMsg struct {
	// Gen — поколение сессии, чьим событием сообщение является. Экран джобы
	// отбрасывает чужие поколения: старый мост остаётся подключённым к той же
	// программе после открытия следующей джобы, и без маркера события прошлой
	// сессии двигали бы состояние новой (WR-05 обзора v0.3.0).
	Gen   int
	Event event.Event
}

// Bridge — второй подписчик событий фазы 8 (первый — печатающий
// internal/render.Printer): превращает событие в сообщение Bubble Tea вместо
// строки. Реализует event.Sink, поэтому доменные пакеты не замечают разницы
// между печатающим режимом и интерфейсом.
//
// До вызова Attach мост молча выбрасывает события — до запуска программы их
// некому показывать, и нулевое состояние обязано быть безопасным, ровно как
// нулевой носитель событий доменных пакетов (event.Emitter).
//
// Мост ничего не накапливает: ни истории событий, ни счётчиков, ни
// последнего шага. Причина та же, что у печатающего подписчика: поле события
// может однажды оказаться носителем чужого секрета, и живущий в процессе
// буфер продлил бы ему жизнь.
type Bridge struct {
	mu sync.Mutex
	// send — функция отправки сообщения в программу Bubble Tea; ставится
	// вызовом Attach после создания программы, потому что раньше её не
	// существует.
	send func(tea.Msg)
	// gen — поколение сессии, к которой мост подключён; ставится при
	// создании и больше не меняется.
	gen int
}

// Проверка соответствия интерфейсу event.Sink на этапе компиляции — тот же
// приём, что у печатающего подписчика (internal/render.Printer) и у клиента
// провайдера (internal/provider/gitlab.Client).
var _ event.Sink = (*Bridge)(nil)

// NewBridge создаёт мост поколения gen без функции отправки: до вызова
// Attach события молча выбрасываются.
func NewBridge(gen int) *Bridge {
	return &Bridge{gen: gen}
}

// Attach подключает функцию отправки сообщения в программу. Вызывается ровно
// один раз, из internal/ui/app.go, после того как программа Bubble Tea уже
// создана.
func (b *Bridge) Attach(send func(tea.Msg)) {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.send = send
}

// Emit реализует event.Sink. Мьютекс обязателен, а не для красоты: подписчик
// получает события и из основной горутины, и из горутины, копирующей
// стандартный вывод дочернего процесса, — требование потокобезопасности
// зафиксировано комментарием у интерфейса подписчика в фазе 8, и этот
// подписчик его наследует. Отправка делается вне удержания мьютекса: она
// блокирующая, и удержание на её время связало бы горутину прогона шагов с
// горутиной этапов.
func (b *Bridge) Emit(e event.Event) {
	b.mu.Lock()
	send := b.send
	b.mu.Unlock()
	if send == nil {
		return
	}
	send(EventMsg{Gen: b.gen, Event: e})
}
