// recover.go — перехват паники, восстановление терминала и честный отчёт
// (Фаза 12, POL-04). Терминал получил интерфейс целиком (альтернативный
// экран) и обязан вернуть его в рабочее состояние, даже падая — контракт
// «Возврат из шелла» и «Ошибки внутри интерфейса» (idea-0.3.0 §7), формализующий
// отложенный фазой 9 пункт реестра угроз T-09-07.
package ui

import (
	"errors"
	"fmt"
	"io"
	"runtime/debug"
	"sync/atomic"
)

// ErrRenderPanic — ошибка-часовой: интерфейс упал при отрисовке.
// Оркестратор (cmd/ci/main.go) отличает её от доменных поломок сверкой
// цепочки ошибок (errors.Is) и печатает свой текст со следующим шагом.
var ErrRenderPanic = errors.New("интерфейс упал при отрисовке")

// panicRecord — запись о панике: динамический тип значения паники строкой и
// трассировка стека. Значения паники в записи нет вовсе — оно передавалось
// в точке падения и могло собраться из переменных окружения или ответа
// API, а то, что интерфейс обязан скрывать, не должно уехать с ним в
// отчёт. Динамический тип и трассировка называют место и природу падения,
// но не данные (T-12-07).
type panicRecord struct {
	Type  string
	Stack string
}

// renderPanic — атомарная запись о первой панике; последующие панике её не
// затирают (см. recordPanic ниже) — интерфейс перерисовывается десятки раз
// в секунду, и без «первая выигрывает» стабильная паника в отрисовке
// затёрла бы исходную запись копией самой себя (T-12-11).
var renderPanic atomic.Pointer[panicRecord]

// recordPanic собирает запись о панике v: тип берётся форматированием по
// динамическому типу (%T), трассировка — стандартной функцией снятия стека
// (runtime/debug.Stack). Значение v в текст не превращается ни одним
// способом. Запись кладётся только если места ещё нет (CompareAndSwap).
func recordPanic(v any) {
	rec := &panicRecord{
		Type:  fmt.Sprintf("%T", v),
		Stack: string(debug.Stack()),
	}
	renderPanic.CompareAndSwap(nil, rec)
}

// guard — единственный перехват в проекте: выполняет body, отложенным
// восстановлением ловит панику, записывает её (recordPanic) и возвращает
// ErrRenderPanic. При отсутствии паники возвращает nil. Одна функция вместо
// трёх обёрток разной формы: у Init/Update/View корневой модели (internal/ui/app.go)
// разные сигнатуры возврата, и три обёртки разошлись бы поведением на
// первой же правке.
func guard(body func()) (err error) {
	defer func() {
		if r := recover(); r != nil {
			recordPanic(r)
			err = ErrRenderPanic
		}
	}()
	body()
	return nil
}

// PanicFrame — кадр, который рисуется вместо экрана после перехвата
// (internal/ui/app.go, View): одна строка ролью отказа с типом паники на
// месте подстановки и следующим шагом, ниже — приглушённая строка о
// восстановлении терминала. Кадр полный, а не поверх прежнего — контракт
// «Вход и выход» (09-UI-SPEC.md) требует полной перерисовки везде, где кадр
// мог остаться недорисованным, а паника в отрисовке — ровно такой случай.
func PanicFrame(t Theme, width, height int) string {
	_ = height // высота кадру отказа не нужна: это две строки, а не панель
	typ := "неизвестная паника"
	if rec := renderPanic.Load(); rec != nil {
		typ = rec.Type
	}
	line1 := fmt.Sprintf("сбой отрисовки интерфейса (%s) — нажмите q, чтобы выйти", typ)
	line2 := "терминал будет восстановлен, подробности уйдут в поток ошибок"
	if width > 0 {
		line1, line2 = Truncate(line1, width), Truncate(line2, width)
	}
	return t.Danger.Render(line1) + "\n\n" + t.Muted.Render(line2)
}

// RestoreTerminal — гарантированное восстановление: показать курсор, выйти
// из альтернативного экрана, выключить отслеживание мыши (обычный и SGR
// режимы), выключить скобочную вставку, сбросить оформление —
// последовательностями в поток вывода w. Своих настроек устройства
// терминала здесь нет — инвариант плана 09-02 остаётся дословно —
// последовательности идемпотентны, поэтому функция безопасна к повторному
// вызову, в том числе после штатного завершения.
func RestoreTerminal(w io.Writer) {
	fmt.Fprint(w,
		"\x1b[?25h",   // показать курсор
		"\x1b[?1049l", // выйти из альтернативного экрана
		"\x1b[?1000l", // выключить отслеживание мыши
		"\x1b[?1006l", // выключить SGR-режим отслеживания мыши
		"\x1b[?2004l", // выключить скобочную вставку
		"\x1b[0m",     // сбросить оформление
	)
}

// ReportPanic печатает честный отчёт о панике rec в поток w: тип и
// трассировка стека, без единого символа исходного значения паники.
// Печатается ПОСЛЕ восстановления терминала (RestoreTerminal), а не до —
// иначе отчёт ушёл бы в альтернативный экран и исчез вместе с ним, и
// восстановление проглотило бы поломку, сделав её невидимой (T-12-10).
func ReportPanic(w io.Writer, rec *panicRecord) {
	if rec == nil {
		return
	}
	fmt.Fprintf(w, "интерфейс упал при отрисовке: %s\n%s\n", rec.Type, rec.Stack)
}
