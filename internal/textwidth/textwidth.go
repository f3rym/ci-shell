// Package textwidth отвечает на один вопрос — сколько ячеек терминала
// занимает строка — и на три производных: обрезать, дополнить, вписать.
// Пакет — лист графа зависимостей проекта: ни одного пакета проекта не
// импортирует, поэтому доменные пакеты (internal/render, internal/runner) и
// пакет интерфейса могут им пользоваться, не создавая цикла с пакетом
// интерфейса — тот уже импортирует пакет печати ради решения о показе
// значения переменной (план 09-02), и второй такой связи заводить нельзя.
// Импорт у пакета ровно один — Lip Gloss.
//
// Мера ширины в проекте одна (POL-02, Фаза 12): байтовая длина форматного
// глагола (`%-Ns`) и срез рун ломаются на кириллице и на составных
// графемных кластерах — оба класса дефектов уже случались (01-REVIEW.md
// IN-01) и здесь недопустимы. Единственная мера — графемная, той же
// библиотекой, что уже красит и собирает раскладку экрана.
package textwidth

import (
	"charm.land/lipgloss/v2"
)

// Plain очищает пользовательскую строку перед измерением и выводом. Имя
// джобы, имя ветки и заголовок коммита приходят от чужого сервера (GitLab
// API), и последовательность управления терминалом внутри них увела бы
// терминал в чужой режим прямо посреди кадра (T-12-01). Перевод строки и
// табуляция в ячейку колонки не попадают вовсе — они заменяются пробелом, а
// не вырезаются, чтобы соседние слова не склеились в одно. Остальной
// диапазон C0, байт DEL и escape-последовательности (CSI и OSC) вырезаются
// целиком. Очистка идёт первой строкой в Truncate и Pad ниже — не по вкусу
// вызывающего.
func Plain(s string) string {
	runes := []rune(s)
	out := make([]rune, 0, len(runes))
	for i := 0; i < len(runes); i++ {
		r := runes[i]
		switch {
		case r == '\n', r == '\t':
			out = append(out, ' ')
		case r == 0x1b:
			// Escape-последовательность: CSI и OSC вырезаются целиком вместе
			// с телом, прочие двухбайтовые формы — сам вводный символ уже
			// пропущен переходом i++ ниже.
			i++
			if i >= len(runes) {
				break
			}
			switch runes[i] {
			case '[':
				i++
				for i < len(runes) && !(runes[i] >= 0x40 && runes[i] <= 0x7e) {
					i++
				}
			case ']':
				i++
				for i < len(runes) && runes[i] != 0x07 {
					if runes[i] == 0x1b && i+1 < len(runes) && runes[i+1] == '\\' {
						i++
						break
					}
					i++
				}
			}
		case r == 0x7f:
			// DEL — управляющий байт, не печатный символ.
		case r < 0x20:
			// Остальной диапазон C0 — управляющие байты, отбрасываются.
		default:
			out = append(out, r)
		}
	}
	return string(out)
}

// Of — ширина s в ячейках терминала: очистка, затем графемная мера Lip
// Gloss. Измерение осведомлено о графемных кластерах и о
// последовательностях оформления, поэтому байтовая длина и длина среза рун
// здесь неприменимы обе — кириллица шире одного байта на символ, а
// составные кластеры длиннее одной руны (09-UI-SPEC.md, «Правило измерения
// ширины»).
func Of(s string) int {
	return lipgloss.Width(Plain(s))
}

// Truncate обрезает s до max ячеек, добавляя многоточие «…» при обрезке.
// Если строка уже уже max — возвращается как есть. Обрезкой занимается сама
// библиотека (ограничение максимальной ширины стиля) — своего обхода по
// графемным кластерам в проекте не появляется. Неположительный max даёт
// пустую строку.
func Truncate(s string, max int) string {
	s = Plain(s)
	if max <= 0 {
		return ""
	}
	if lipgloss.Width(s) <= max {
		return s
	}
	return lipgloss.NewStyle().MaxWidth(max-1).Render(s) + "…"
}

// Pad дополняет s до ровно width ячеек по левому краю стилем Lip Gloss —
// замена ручного выравнивания форматным глаголом (`%-Ns`): тот считает
// байты и потому ломается на любой русской подписи.
func Pad(s string, width int) string {
	s = Plain(s)
	return lipgloss.NewStyle().Width(width).Render(s)
}

// Fit приводит s ровно к ширине width: сначала Truncate, затем Pad. Строка
// занимает ровно width ячеек, чем бы она ни была.
func Fit(s string, width int) string {
	return Pad(Truncate(s, width), width)
}
