package runner

import (
	"context"
	"io"

	"github.com/f3rym/ci-shell/internal/render"
)

// CleanRun поднимает свежий контейнер по уже готовой спецификации spec —
// образ, каталог кода, рабочий каталог, окружение, каталог файловых
// переменных и точка их монтирования обязаны совпадать с первым
// контейнером, иначе «чистый прогон» проверял бы не ту джобу, поэтому
// спецификация принимается параметром и не пересобирается здесь. Второй
// контейнер ничего не знает о сессии первого, а код на диске — тот же
// самый, уже исправленный: каталог смонтирован с хоста. Это и есть
// единственная честная проверка «в CI будет зелено» (третий уровень
// доверия, idea-0.2.0 §1).
func CleanRun(ctx context.Context, d *Docker, spec Spec, steps []Step, out, errOut io.Writer, p render.Progress) (Outcome, error) {
	p.Stage("поднимаю свежий контейнер из образа %s для чистого прогона…", spec.Image)

	c, _, err := d.Start(ctx, spec)
	if err != nil {
		return Outcome{}, err
	}
	// Фоновый контекст: прерывание пользователем во время чистого прогона
	// не должно оставить второй контейнер на машине. Неудача снятия не
	// фатальна — печатается предупреждением с сокращённым id и готовой
	// командой добивки, тем же приёмом, что уже использует уборка чекаута.
	defer func() {
		if err := c.Remove(context.Background()); err != nil {
			p.Stage("предупреждение: %s; добейте вручную: docker rm -f %s", err, c.ID)
		}
	}()

	// Оболочка выбирается заново: контейнер новый, прежняя проба к нему не
	// относится.
	if err := c.DetectShell(ctx); err != nil {
		return Outcome{}, err
	}

	// Все шаги джобы, а не только оставшиеся: смысл третьего уровня
	// доверия ровно в том, что проверяется весь путь с нуля.
	return RunSteps(ctx, c, steps, out, errOut, p)
}
