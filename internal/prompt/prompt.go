// Package prompt держит единственный на процесс буферизованный читатель
// стандартного ввода.
//
// Читатель именно один, и это не про экономию: bufio.NewReader за раз
// вычитывает из дескриптора до 4096 байт, и всё, что читатель забуферизовал
// после первой строки, пропадает вместе с ним. Свой bufio.NewReader(os.Stdin)
// на каждый вопрос означал, что один запуск, задающий до трёх вопросов
// подряд (токен → каталог чекаутов → чистый прогон), терял хвост
// вставленного или переданного по пайпу ввода после первой же строки: второй
// вопрос читал уже пустоту, а вопрос о чистом прогоне получал EOF и молча
// отвечал «нет».
package prompt

import (
	"bufio"
	"os"
)

// reader — тот самый единственный читатель. Создаётся один раз при
// инициализации пакета, буфер живёт весь процесс.
var reader = bufio.NewReader(os.Stdin)

// Line читает одну строку стандартного ввода вместе с переводом строки.
// Ошибка возвращается как есть — решение о том, считать ли оборванное
// чтение отказом или согласием с умолчанием, принимает вызывающий: у
// каждого вопроса оно своё.
func Line() (string, error) {
	return reader.ReadString('\n')
}
