// Package term определяет возможности терминала, которыми располагает
// процесс. Только стандартная библиотека: внешний пакет определения TTY в
// go.mod не добавляется ни сейчас, ни в Фазе 9.
//
// Пакет отдельный от проверки терминала в internal/token (token.Interactive):
// та отвечает «есть ли кого спросить» и смотрит только стандартный ввод,
// потому что её единственная задача — не подвесить процесс вопросом в
// пайпе. Здесь вопрос другой — «есть ли где рисовать полноэкранный
// интерфейс», и для него мало ввода: интерфейс и читает клавиши, и
// перерисовывает экран.
package term

import (
	"os"
)

// dumbTerminal — значение переменной TERM, означающее «терминал не умеет
// позиционировать курсор». Названо константой затем, что и UIEnabled ниже, и
// ColorDisabled (Фаза 12, POL-01) проверяют его одной и той же строкой —
// второго определения «немой терминал» в проекте быть не должно.
const dumbTerminal = "dumb"

// IsTTY истинна, когда И стандартный ввод, И стандартный вывод являются
// символьными устройствами. Любая ошибка получения сведений о файле — ложь:
// неизвестное состояние трактуется как «терминала нет», потому что цена
// ошибки несимметрична (запустить интерфейс в пайпе хуже, чем не запустить
// его в терминале).
func IsTTY() bool {
	in, err := os.Stdin.Stat()
	if err != nil {
		return false
	}
	out, err := os.Stdout.Stat()
	if err != nil {
		return false
	}
	return in.Mode()&os.ModeCharDevice != 0 && out.Mode()&os.ModeCharDevice != 0
}

// UIEnabled — единственная точка решения о запуске интерфейса во всём
// проекте. Истинна, когда одновременно:
//   - IsTTY() истинна;
//   - переменная окружения TERM непуста и не равна "dumb" — терминал,
//     объявивший себя таковым, не умеет позиционировать курсор, и
//     полноэкранный вывод в нём превращается в мусор;
//   - переменная окружения CI_SHELL_NO_UI пуста — явный выключатель для
//     того, кто хочет старое поведение в интерактивной оболочке (обёртки,
//     демонстрации, отладка вывода). Имя переменной согласовано с уже
//     существующей CI_SHELL_TOKEN.
//
// Второй такой проверки в проекте быть не должно: Фаза 9 вешает запуск
// интерфейса на истинную ветку этой функции и не заводит собственного
// условия — иначе «интерфейс не запускается без TTY» станет утверждением
// про два места сразу, и одно из них рано или поздно разойдётся со вторым.
func UIEnabled() bool {
	if !IsTTY() {
		return false
	}
	t := os.Getenv("TERM")
	if t == "" || t == dumbTerminal {
		return false
	}
	if os.Getenv("CI_SHELL_NO_UI") != "" {
		return false
	}
	return true
}

// ColorDisabled — единственная точка решения о выключенном цвете во всём
// проекте (Фаза 12, POL-01). Истинна, когда:
//   - переменная окружения NO_COLOR непуста — соглашение окружения
//     (https://no-color.org), которое утилита обязана уважать безусловно, а
//     не наша выдумка;
//   - либо переменная окружения TERM пуста или равна dumbTerminal — та же
//     константа и тот же приём, что уже применяет UIEnabled выше; второй
//     такой проверки в проекте появляться не должно.
func ColorDisabled() bool {
	if os.Getenv("NO_COLOR") != "" {
		return true
	}
	t := os.Getenv("TERM")
	return t == "" || t == dumbTerminal
}
